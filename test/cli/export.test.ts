import { appendFile, cp, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, expect, it } from 'vite-plus/test';
import { scratchDir } from '../scratch.ts';
import { fixtureRoot, runCli } from './run.ts';

const SCENARIO_A = `Scenario: Zero balance
  Given a new client
  Then its balance is 0`;

const SCENARIO_B = `Scenario: Second account

  Given a client with an account
  When another account is opened
  Then it is rejected`;

async function repoWithScenarios(): Promise<string> {
  const dir = await scratchDir();
  await cp(fixtureRoot('repo'), dir, { recursive: true });
  await appendBody(
    dir,
    'billing/R-BIL-001.md',
    `\n\`\`\`gherkin\n${SCENARIO_A}\n\`\`\`\n\nMore text.\n\n\`\`\`gherkin\n${SCENARIO_B}\n\`\`\`\n`,
  );
  await appendBody(
    dir,
    'clients/R-CLI-002.md',
    `\n\`\`\`gherkin\nScenario: Proposed\n  Given a draft\n\`\`\`\n`,
  );
  await appendBody(
    dir,
    'clients/R-CLI-003.md',
    `\n\`\`\`gherkin\nScenario: Deprecated\n  Given an old rule\n\`\`\`\n`,
  );
  return dir;
}

async function appendBody(dir: string, rule: string, text: string): Promise<void> {
  await appendFile(join(dir, 'docs/rules', rule), text);
}

describe('export gherkin', () => {
  it('writes one .feature per non-deprecated rule with scenarios, tagged with the rule id', async () => {
    const dir = await repoWithScenarios();

    expect(await runCli(['export', 'gherkin'], dir)).toEqual({
      status: 0,
      stdout: [
        'features/rules/billing/R-BIL-001.feature',
        'features/rules/clients/R-CLI-002.feature',
        '',
      ].join('\n'),
      stderr: '',
    });
    expect(await readFile(join(dir, 'features/rules/billing/R-BIL-001.feature'), 'utf8')).toBe(
      [
        '# Generated by "rulebookguard export gherkin" from docs/rules/billing/R-BIL-001.md; edit the rule instead.',
        '@R-BIL-001',
        'Feature: R-BIL-001 Every new client gets a zero-balance account.',
        '',
        '  Scenario: Zero balance',
        '    Given a new client',
        '    Then its balance is 0',
        '',
        '  Scenario: Second account',
        '',
        '    Given a client with an account',
        '    When another account is opened',
        '    Then it is rejected',
        '',
      ].join('\n'),
    );
    expect(await readdir(join(dir, 'features/rules/clients'))).toEqual(['R-CLI-002.feature']);
  });

  it('writes Spanish keywords and drops the language lines of the blocks', async () => {
    const dir = await scratchDir();
    await cp(fixtureRoot('repo'), dir, { recursive: true });
    await appendFile(join(dir, 'rulebookguard.config.yaml'), 'language: es\n');
    await appendBody(
      dir,
      'billing/R-BIL-001.md',
      '\n```gherkin\n# language: es\nEscenario: Saldo cero\n  Dado un cliente nuevo\n```\n',
    );

    expect((await runCli(['export', 'gherkin', '--out', 'out'], dir)).stdout).toBe(
      'out/billing/R-BIL-001.feature\n',
    );
    expect(await readFile(join(dir, 'out/billing/R-BIL-001.feature'), 'utf8')).toBe(
      [
        '# language: es',
        '# Generado por "rulebookguard export gherkin" desde docs/rules/billing/R-BIL-001.md; edita la regla en su lugar.',
        '@R-BIL-001',
        'Característica: R-BIL-001 Every new client gets a zero-balance account.',
        '',
        '  Escenario: Saldo cero',
        '    Dado un cliente nuevo',
        '',
      ].join('\n'),
    );
  });

  it('overwrites a generated file and leaves other files of the output directory alone', async () => {
    const dir = await repoWithScenarios();
    await mkdir(join(dir, 'features/rules/billing'), { recursive: true });
    await writeFile(join(dir, 'features/rules/billing/R-BIL-001.feature'), 'stale\n');
    await writeFile(join(dir, 'features/rules/steps.ts'), 'keep\n');

    expect((await runCli(['export', 'gherkin'], dir)).status).toBe(0);
    expect(await readFile(join(dir, 'features/rules/billing/R-BIL-001.feature'), 'utf8')).toContain(
      '@R-BIL-001',
    );
    expect(await readFile(join(dir, 'features/rules/steps.ts'), 'utf8')).toBe('keep\n');
  });

  it('says so when no rule has scenarios', async () => {
    expect(await runCli(['export', 'gherkin'], fixtureRoot('repo'))).toEqual({
      status: 0,
      stdout: 'No rule has Gherkin scenarios.\n',
      stderr: '',
    });
  });

  it('rejects an unknown format', async () => {
    expect(await runCli(['export', 'cucumber'], fixtureRoot('repo'))).toEqual({
      status: 2,
      stdout: '',
      stderr:
        'Unknown export format "cucumber"; supported: gherkin.\nUsage: rulebookguard export <format> [--out <dir>]\n',
    });
  });
});
