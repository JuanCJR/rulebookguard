import { appendFile, cp, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, expect, it } from 'vite-plus/test';
import { scratchDir } from '../scratch.ts';
import { fixtureRoot, runCli } from './run.ts';

const SCENARIO_A = `Scenario: Zero balance
  Given a new client
  Then its balance is 0`;

const SCENARIO_B = `Scenario: Second account

  Given a client with an account
  When another account is opened
  Then it is rejected`;

async function repoWithScenarios(): Promise<string> {
  const dir = await scratchDir();
  await cp(fixtureRoot('repo'), dir, { recursive: true });
  await appendBody(
    dir,
    'billing/R-BIL-001.md',
    `\n\`\`\`gherkin\n${SCENARIO_A}\n\`\`\`\n\nMore text.\n\n\`\`\`gherkin\n${SCENARIO_B}\n\`\`\`\n`,
  );
  await appendBody(
    dir,
    'clients/R-CLI-002.md',
    `\n\`\`\`gherkin\nScenario: Proposed\n  Given a draft\n\`\`\`\n`,
  );
  await appendBody(
    dir,
    'clients/R-CLI-003.md',
    `\n\`\`\`gherkin\nScenario: Deprecated\n  Given an old rule\n\`\`\`\n`,
  );
  return dir;
}

async function appendBody(dir: string, rule: string, text: string): Promise<void> {
  await appendFile(join(dir, 'docs/rules', rule), text);
}

describe('export gherkin', () => {
  it('writes one .feature per non-deprecated rule with scenarios, tagged with the rule id', async () => {
    const dir = await repoWithScenarios();

    expect(await runCli(['export', 'gherkin'], dir)).toEqual({
      status: 0,
      stdout: [
        'features/rules/billing/R-BIL-001.feature',
        'features/rules/clients/R-CLI-002.feature',
        '',
      ].join('\n'),
      stderr: '',
    });
    expect(await readFile(join(dir, 'features/rules/billing/R-BIL-001.feature'), 'utf8')).toBe(
      [
        '# Generated by "rulebookguard export gherkin" from docs/rules/billing/R-BIL-001.md; edit the rule instead.',
        '@R-BIL-001',
        'Feature: R-BIL-001 Every new client gets a zero-balance account.',
        '',
        '  Scenario: Zero balance',
        '    Given a new client',
        '    Then its balance is 0',
        '',
        '  Scenario: Second account',
        '',
        '    Given a client with an account',
        '    When another account is opened',
        '    Then it is rejected',
        '',
      ].join('\n'),
    );
    expect(await readdir(join(dir, 'features/rules/clients'))).toEqual(['R-CLI-002.feature']);
  });

  it('writes Spanish keywords and drops the language lines of the blocks', async () => {
    const dir = await scratchDir();
    await cp(fixtureRoot('repo'), dir, { recursive: true });
    await appendFile(join(dir, 'rulebookguard.config.yaml'), 'language: es\n');
    await appendBody(
      dir,
      'billing/R-BIL-001.md',
      '\n```gherkin\n# language: es\nEscenario: Saldo cero\n  Dado un cliente nuevo\n```\n',
    );

    expect((await runCli(['export', 'gherkin', '--out', 'out'], dir)).stdout).toBe(
      'out/billing/R-BIL-001.feature\n',
    );
    expect(await readFile(join(dir, 'out/billing/R-BIL-001.feature'), 'utf8')).toBe(
      [
        '# language: es',
        '# Generado por "rulebookguard export gherkin" desde docs/rules/billing/R-BIL-001.md; edita la regla en su lugar.',
        '@R-BIL-001',
        'Característica: R-BIL-001 Every new client gets a zero-balance account.',
        '',
        '  Escenario: Saldo cero',
        '    Dado un cliente nuevo',
        '',
      ].join('\n'),
    );
  });

  it('overwrites a generated file and leaves other files of the output directory alone', async () => {
    const dir = await repoWithScenarios();
    await mkdir(join(dir, 'features/rules/billing'), { recursive: true });
    await writeFile(join(dir, 'features/rules/billing/R-BIL-001.feature'), 'stale\n');
    await writeFile(join(dir, 'features/rules/steps.ts'), 'keep\n');

    expect((await runCli(['export', 'gherkin'], dir)).status).toBe(0);
    expect(await readFile(join(dir, 'features/rules/billing/R-BIL-001.feature'), 'utf8')).toContain(
      '@R-BIL-001',
    );
    expect(await readFile(join(dir, 'features/rules/steps.ts'), 'utf8')).toBe('keep\n');
  });

  it('says so when no rule has scenarios', async () => {
    expect(await runCli(['export', 'gherkin'], fixtureRoot('repo'))).toEqual({
      status: 0,
      stdout: 'No rule has Gherkin scenarios.\n',
      stderr: '',
    });
  });

  it('rejects an unknown format', async () => {
    expect(await runCli(['export', 'cucumber'], fixtureRoot('repo'))).toEqual({
      status: 2,
      stdout: '',
      stderr:
        'Unknown export format "cucumber"; supported: gherkin, cursor, copilot, kiro.\nUsage: rulebookguard export <format> [--out <dir>]\n',
    });
  });
});

async function dropAnchors(dir: string, file: string): Promise<void> {
  const rule = join(dir, 'docs/rules', file);
  await writeFile(
    rule,
    (await readFile(rule, 'utf8')).replace(/anchors:\r?\n(?: {2}- .*\r?\n)+/, 'anchors: []\n'),
  );
}

async function repoCopy(): Promise<string> {
  const dir = await scratchDir();
  await cp(fixtureRoot('repo'), dir, { recursive: true });
  return dir;
}

const BODY =
  '# Zero-balance account\n\nCreating a client opens a billing account with balance 0.\n';

describe('export kiro', () => {
  it('writes one fileMatch steering file per active rule, with its anchors as patterns', async () => {
    const dir = await repoCopy();

    expect(await runCli(['export', 'kiro'], dir)).toEqual({
      status: 0,
      stdout: [
        '.kiro/steering/rulebookguard-R-BIL-001.md',
        '.kiro/steering/rulebookguard-R-BIL-002.md',
        '.kiro/steering/rulebookguard-R-CLI-001.md',
        '',
      ].join('\n'),
      stderr: '',
    });
    expect(await readFile(join(dir, '.kiro/steering/rulebookguard-R-BIL-001.md'), 'utf8')).toBe(
      [
        '---',
        'inclusion: fileMatch',
        'fileMatchPattern: ["src/billing/**","src/clients/create.go"]',
        '---',
        '',
        '<!-- Generated by "rulebookguard export kiro" from docs/rules/billing/R-BIL-001.md; edit the rule instead. -->',
        '',
        '**R-BIL-001:** Every new client gets a zero-balance account.',
        '',
        BODY,
      ].join('\n'),
    );
  });

  it('writes a single anchor as a plain pattern', async () => {
    const dir = await repoCopy();

    await runCli(['export', 'kiro'], dir);

    expect(
      await readFile(join(dir, '.kiro/steering/rulebookguard-R-CLI-001.md'), 'utf8'),
    ).toContain('\nfileMatchPattern: "src/clients/**/*.go"\n');
  });

  it('writes the generated line in the language of the rulebook', async () => {
    const dir = await repoCopy();
    await appendFile(join(dir, 'rulebookguard.config.yaml'), 'language: es\n');

    await runCli(['export', 'kiro'], dir);

    expect(
      await readFile(join(dir, '.kiro/steering/rulebookguard-R-BIL-002.md'), 'utf8'),
    ).toContain(
      '<!-- Generado por "rulebookguard export kiro" desde docs/rules/billing/R-BIL-002.md; edita la regla en su lugar. -->',
    );
  });
});

describe('export cursor', () => {
  it('writes one auto-attached .mdc per active rule, with its anchors as comma-separated globs', async () => {
    const dir = await repoCopy();

    expect((await runCli(['export', 'cursor'], dir)).stdout).toBe(
      [
        '.cursor/rules/rulebookguard-R-BIL-001.mdc',
        '.cursor/rules/rulebookguard-R-BIL-002.mdc',
        '.cursor/rules/rulebookguard-R-CLI-001.mdc',
        '',
      ].join('\n'),
    );
    expect(await readFile(join(dir, '.cursor/rules/rulebookguard-R-BIL-001.mdc'), 'utf8')).toBe(
      [
        '---',
        'globs: src/billing/**, src/clients/create.go',
        'alwaysApply: false',
        '---',
        '',
        '<!-- Generated by "rulebookguard export cursor" from docs/rules/billing/R-BIL-001.md; edit the rule instead. -->',
        '',
        '**R-BIL-001:** Every new client gets a zero-balance account.',
        '',
        BODY,
      ].join('\n'),
    );
  });
});

describe('export copilot', () => {
  it('writes one instructions file per active rule, with its anchors in applyTo', async () => {
    const dir = await repoCopy();

    expect((await runCli(['export', 'copilot'], dir)).stdout).toBe(
      [
        '.github/instructions/rulebookguard-R-BIL-001.instructions.md',
        '.github/instructions/rulebookguard-R-BIL-002.instructions.md',
        '.github/instructions/rulebookguard-R-CLI-001.instructions.md',
        '',
      ].join('\n'),
    );
    expect(
      await readFile(
        join(dir, '.github/instructions/rulebookguard-R-BIL-001.instructions.md'),
        'utf8',
      ),
    ).toBe(
      [
        '---',
        'applyTo: "src/billing/**,src/clients/create.go"',
        '---',
        '',
        '<!-- Generated by "rulebookguard export copilot" from docs/rules/billing/R-BIL-001.md; edit the rule instead. -->',
        '',
        '**R-BIL-001:** Every new client gets a zero-balance account.',
        '',
        BODY,
      ].join('\n'),
    );
  });

  it('expands brace anchors, whose commas would split the pattern', async () => {
    const dir = await repoCopy();
    const rule = join(dir, 'docs/rules/billing/R-BIL-002.md');
    await writeFile(
      rule,
      (await readFile(rule, 'utf8')).replace('src/billing/invoice.go', 'src/{a,b}/*.{go,ts}'),
    );

    await runCli(['export', 'copilot'], dir);

    expect(
      await readFile(
        join(dir, '.github/instructions/rulebookguard-R-BIL-002.instructions.md'),
        'utf8',
      ),
    ).toContain('\napplyTo: "src/a/*.go,src/a/*.ts,src/b/*.go,src/b/*.ts"\n');
  });
});

describe('export of agent rule files', () => {
  it('removes the generated file of a rule no longer active, and nothing else', async () => {
    const dir = await repoCopy();
    await runCli(['export', 'kiro'], dir);
    const steering = join(dir, '.kiro/steering');
    await writeFile(join(steering, 'rulebookguard-notes.md'), 'written by hand\n');
    await writeFile(join(steering, 'style.md'), 'keep\n');
    const rule = join(dir, 'docs/rules/billing/R-BIL-002.md');
    await writeFile(
      rule,
      (await readFile(rule, 'utf8')).replace('status: active', 'status: deprecated'),
    );

    expect((await runCli(['export', 'kiro'], dir)).stdout).toBe(
      [
        '.kiro/steering/rulebookguard-R-BIL-001.md',
        '.kiro/steering/rulebookguard-R-CLI-001.md',
        'removed .kiro/steering/rulebookguard-R-BIL-002.md',
        '',
      ].join('\n'),
    );
    expect((await readdir(steering)).sort()).toEqual([
      'rulebookguard-R-BIL-001.md',
      'rulebookguard-R-CLI-001.md',
      'rulebookguard-notes.md',
      'style.md',
    ]);
  });

  it('refuses to overwrite a hand-written file of an active rule, writing and removing nothing', async () => {
    const dir = await repoCopy();
    await runCli(['export', 'kiro'], dir);
    const steering = join(dir, '.kiro/steering');
    const generated = await readFile(join(steering, 'rulebookguard-R-BIL-001.md'), 'utf8');
    await writeFile(join(steering, 'rulebookguard-R-BIL-001.md'), `${generated}\nstale\n`);
    await writeFile(join(steering, 'rulebookguard-R-CLI-001.md'), 'written by hand\n');
    const rule = join(dir, 'docs/rules/billing/R-BIL-002.md');
    await writeFile(
      rule,
      (await readFile(rule, 'utf8')).replace('status: active', 'status: deprecated'),
    );

    expect(await runCli(['export', 'kiro'], dir)).toEqual({
      status: 1,
      stdout: '',
      stderr:
        '.kiro/steering/rulebookguard-R-CLI-001.md was not generated by "rulebookguard export kiro"; move it away and run the export again.\n',
    });
    expect(await readFile(join(steering, 'rulebookguard-R-CLI-001.md'), 'utf8')).toBe(
      'written by hand\n',
    );
    expect(await readFile(join(steering, 'rulebookguard-R-BIL-001.md'), 'utf8')).toBe(
      `${generated}\nstale\n`,
    );
    expect(await readdir(steering)).toContain('rulebookguard-R-BIL-002.md');
  });

  it('overwrites a file it generated, even after its text was edited', async () => {
    const dir = await repoCopy();
    await runCli(['export', 'cursor'], dir);
    const file = join(dir, '.cursor/rules/rulebookguard-R-CLI-001.mdc');
    const generated = await readFile(file, 'utf8');
    await writeFile(file, `${generated}\nedited\n`);

    expect((await runCli(['export', 'cursor'], dir)).status).toBe(0);
    expect(await readFile(file, 'utf8')).toBe(generated);
  });

  it('removes a generated file written in Spanish', async () => {
    const dir = await repoCopy();
    await appendFile(join(dir, 'rulebookguard.config.yaml'), 'language: es\n');
    await runCli(['export', 'kiro'], dir);
    const rule = join(dir, 'docs/rules/billing/R-BIL-002.md');
    await writeFile(
      rule,
      (await readFile(rule, 'utf8')).replace('status: active', 'status: deprecated'),
    );

    expect((await runCli(['export', 'kiro'], dir)).stdout).toContain(
      'eliminado .kiro/steering/rulebookguard-R-BIL-002.md\n',
    );
    expect(await readdir(join(dir, '.kiro/steering'))).not.toContain('rulebookguard-R-BIL-002.md');
  });

  it('removes a generated file checked out with CRLF line endings', async () => {
    const dir = await repoCopy();
    await runCli(['export', 'kiro'], dir);
    const generated = join(dir, '.kiro/steering/rulebookguard-R-BIL-002.md');
    await writeFile(generated, (await readFile(generated, 'utf8')).replaceAll('\n', '\r\n'));
    const rule = join(dir, 'docs/rules/billing/R-BIL-002.md');
    await writeFile(
      rule,
      (await readFile(rule, 'utf8')).replace('status: active', 'status: deprecated'),
    );

    expect((await runCli(['export', 'kiro'], dir)).stdout).toContain(
      'removed .kiro/steering/rulebookguard-R-BIL-002.md\n',
    );
  });

  it.each([
    ['has no generated line', '# Notes\n'],
    ['only mentions the command', 'Refresh with "rulebookguard export kiro" when rules change.\n'],
    [
      'has the line after its own text',
      '---\ninclusion: manual\n---\n\nNotes.\n\n<!-- Generated by "rulebookguard export kiro" from x.md -->\n',
    ],
    [
      'has the line of another format',
      '---\nglobs: a\n---\n\n<!-- Generated by "rulebookguard export cursor" from x.md; edit the rule instead. -->\n',
    ],
  ])('keeps a hand-written file named after a rule id that %s', async (_case, content) => {
    const dir = await repoCopy();
    const steering = join(dir, '.kiro/steering');
    await mkdir(steering, { recursive: true });
    await writeFile(join(steering, 'rulebookguard-R-BIL-999.md'), content);

    expect((await runCli(['export', 'kiro'], dir)).stdout).not.toContain('removed');
    expect(await readFile(join(steering, 'rulebookguard-R-BIL-999.md'), 'utf8')).toBe(content);
  });

  it('warns about an active rule without anchors and removes its generated file', async () => {
    const dir = await repoCopy();
    await runCli(['export', 'kiro'], dir);
    await dropAnchors(dir, 'billing/R-BIL-002.md');

    expect(await runCli(['export', 'kiro'], dir)).toEqual({
      status: 0,
      stdout: [
        '.kiro/steering/rulebookguard-R-BIL-001.md',
        '.kiro/steering/rulebookguard-R-CLI-001.md',
        'removed .kiro/steering/rulebookguard-R-BIL-002.md',
        '',
      ].join('\n'),
      stderr: 'R-BIL-002 is active but has no anchors, so it was not exported.\n',
    });
  });

  it('says so when no active rule has anchors', async () => {
    const dir = await repoCopy();
    for (const file of ['billing/R-BIL-001.md', 'billing/R-BIL-002.md', 'clients/R-CLI-001.md']) {
      await dropAnchors(dir, file);
    }

    expect(await runCli(['export', 'cursor'], dir)).toEqual({
      status: 0,
      stdout: 'No active rule with anchors to export.\n',
      stderr: [
        'R-BIL-001 is active but has no anchors, so it was not exported.',
        'R-BIL-002 is active but has no anchors, so it was not exported.',
        'R-CLI-001 is active but has no anchors, so it was not exported.',
        '',
      ].join('\n'),
    });
  });

  it('writes under the rulebook root from a subdirectory, and under --out from the current directory', async () => {
    const dir = await repoCopy();
    const sub = join(dir, 'src/clients');

    expect((await runCli(['export', 'cursor'], sub)).status).toBe(0);
    expect(await readdir(join(dir, '.cursor/rules'))).toContain('rulebookguard-R-CLI-001.mdc');

    expect((await runCli(['export', 'cursor', '--out', 'out'], sub)).stdout).toContain(
      'out/rulebookguard-R-CLI-001.mdc\n',
    );
    expect(await readdir(join(sub, 'out'))).toContain('rulebookguard-R-CLI-001.mdc');
  });

  it('says so when no rule is active', async () => {
    const dir = await repoCopy();
    for (const file of ['billing/R-BIL-001.md', 'billing/R-BIL-002.md', 'clients/R-CLI-001.md']) {
      const rule = join(dir, 'docs/rules', file);
      await writeFile(
        rule,
        (await readFile(rule, 'utf8')).replace('status: active', 'status: proposed'),
      );
    }

    expect(await runCli(['export', 'kiro'], dir)).toEqual({
      status: 0,
      stdout: 'No active rule to export.\n',
      stderr: '',
    });
    await expect(readdir(join(dir, '.kiro/steering'))).rejects.toThrow();
  });
});
