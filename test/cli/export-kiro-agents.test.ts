import { appendFile, cp, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, expect, it } from 'vite-plus/test';
import { splitFrontmatter } from '../../src/format/frontmatter.ts';
import { scratchDir } from '../scratch.ts';
import { fixtureRoot, runCli } from './run.ts';

const AUTHOR = '.kiro/agents/rulebookguard-rule-author.md';
const MINER = '.kiro/agents/rulebookguard-rule-miner.md';

const pkg = JSON.parse(await readFile(new URL('../../package.json', import.meta.url), 'utf8')) as {
  version: string;
};

async function repoCopy(): Promise<string> {
  const dir = await scratchDir();
  await cp(fixtureRoot('repo'), dir, { recursive: true });
  return dir;
}

async function exported(file: string): Promise<{ data: Record<string, unknown>; body: string }> {
  const dir = await repoCopy();
  await runCli(['export', 'kiro-agents'], dir);
  const { data, body } = splitFrontmatter(await readFile(join(dir, file), 'utf8'), file);
  return { data: data as Record<string, unknown>, body };
}

describe('export kiro-agents', () => {
  it('writes one Kiro custom agent per plugin agent', async () => {
    const dir = await repoCopy();

    expect(await runCli(['export', 'kiro-agents'], dir)).toEqual({
      status: 0,
      stdout: `${AUTHOR}\n${MINER}\n`,
      stderr: '',
    });
    expect((await readdir(join(dir, '.kiro/agents'))).sort()).toEqual([
      'rulebookguard-rule-author.md',
      'rulebookguard-rule-miner.md',
    ]);
  });

  it.each([
    [AUTHOR, 'rule-author'],
    [MINER, 'rule-miner'],
  ])('gives %s Kiro tools and its own pinned MCP server', async (file, name) => {
    const { data } = await exported(file);

    expect(data).toEqual({
      name,
      description: expect.stringContaining('rulebookguard'),
      tools: ['read', 'write', 'shell', '@rulebookguard'],
      mcpServers: {
        rulebookguard: {
          command: 'npx',
          args: ['--yes', `rulebookguard@${pkg.version}`, 'mcp'],
        },
      },
    });
  });

  it.each([AUTHOR, MINER])('makes %s work without the Claude Code plugin', async (file) => {
    const { body } = await exported(file);

    expect(body).not.toContain('rulebookguard.mjs');
    expect(body).not.toContain('rulebookguard:rule-writing');
    expect(body).not.toContain('preloaded');
    expect(body).toContain(`npx --yes rulebookguard@${pkg.version} new <context>`);
    expect(body).toContain('# Writing a business rule (rulebookguard)');
    expect(body).toContain(
      `<!-- Generated by "rulebookguard export kiro-agents" from rulebookguard ${pkg.version}; run it again to update. -->`,
    );
  });

  it('follows the language of the config in the generated line', async () => {
    const dir = await repoCopy();
    await appendFile(join(dir, 'rulebookguard.config.yaml'), 'language: es\n');

    await runCli(['export', 'kiro-agents'], dir);

    expect(await readFile(join(dir, MINER), 'utf8')).toContain(
      `<!-- Generado por "rulebookguard export kiro-agents" desde rulebookguard ${pkg.version}; vuelve a ejecutarlo para actualizar. -->`,
    );
  });

  it('regenerates its own Spanish files', async () => {
    const dir = await repoCopy();
    await appendFile(join(dir, 'rulebookguard.config.yaml'), 'language: es\n');
    await runCli(['export', 'kiro-agents'], dir);
    const first = await readFile(join(dir, MINER), 'utf8');
    await writeFile(join(dir, MINER), first.replace('You lift', 'You edited'));

    expect(await runCli(['export', 'kiro-agents'], dir)).toEqual({
      status: 0,
      stdout: `${AUTHOR}\n${MINER}\n`,
      stderr: '',
    });
    expect(await readFile(join(dir, MINER), 'utf8')).toBe(first);
  });

  it('regenerates English files in Spanish after the config changes language', async () => {
    const dir = await repoCopy();
    await runCli(['export', 'kiro-agents'], dir);
    await appendFile(join(dir, 'rulebookguard.config.yaml'), 'language: es\n');

    expect((await runCli(['export', 'kiro-agents'], dir)).status).toBe(0);
    expect(await readFile(join(dir, MINER), 'utf8')).toContain(
      '<!-- Generado por "rulebookguard export kiro-agents"',
    );
  });

  it('writes directly in --out', async () => {
    const dir = await repoCopy();

    expect((await runCli(['export', 'kiro-agents', '--out', 'custom'], dir)).stdout).toBe(
      'custom/rulebookguard-rule-author.md\ncustom/rulebookguard-rule-miner.md\n',
    );
  });

  it('overwrites its own files and gives the same result', async () => {
    const dir = await repoCopy();
    await runCli(['export', 'kiro-agents'], dir);
    const first = await readFile(join(dir, AUTHOR), 'utf8');
    await writeFile(join(dir, AUTHOR), first.replace('You design', 'You edited'));

    expect((await runCli(['export', 'kiro-agents'], dir)).status).toBe(0);
    expect(await readFile(join(dir, AUTHOR), 'utf8')).toBe(first);
  });

  it('refuses a hand-written agent before writing anything', async () => {
    const dir = await repoCopy();
    await mkdir(join(dir, '.kiro/agents'), { recursive: true });
    await writeFile(join(dir, MINER), 'written by hand\n');

    expect(await runCli(['export', 'kiro-agents'], dir)).toEqual({
      status: 1,
      stdout: '',
      stderr: `${MINER} was not generated by "rulebookguard export kiro-agents"; move it away and run the export again.\n`,
    });
    expect(await readdir(join(dir, '.kiro/agents'))).toEqual(['rulebookguard-rule-miner.md']);
    expect(await readFile(join(dir, MINER), 'utf8')).toBe('written by hand\n');
  });

  it('leaves the other files of the directory alone', async () => {
    const dir = await repoCopy();
    await mkdir(join(dir, '.kiro/agents'), { recursive: true });
    await writeFile(join(dir, '.kiro/agents/mine.md'), 'my agent\n');

    await runCli(['export', 'kiro-agents'], dir);

    expect(await readFile(join(dir, '.kiro/agents/mine.md'), 'utf8')).toBe('my agent\n');
  });

  it('refuses a steering export sitting at an agent path', async () => {
    const dir = await repoCopy();
    await runCli(['export', 'kiro'], dir);
    const steering = await readFile(join(dir, '.kiro/steering/rulebookguard-R-CLI-001.md'), 'utf8');
    await mkdir(join(dir, '.kiro/agents'), { recursive: true });
    await writeFile(join(dir, MINER), steering);

    expect(await runCli(['export', 'kiro-agents'], dir)).toEqual({
      status: 1,
      stdout: '',
      stderr: `${MINER} was not generated by "rulebookguard export kiro-agents"; move it away and run the export again.\n`,
    });
    expect(await readFile(join(dir, MINER), 'utf8')).toBe(steering);
  });

  it('shares an --out directory with the steering export without either removing files', async () => {
    const dir = await repoCopy();
    await runCli(['export', 'kiro', '--out', 'shared'], dir);
    await runCli(['export', 'kiro-agents', '--out', 'shared'], dir);
    const both = (await readdir(join(dir, 'shared'))).sort();

    const steering = await runCli(['export', 'kiro', '--out', 'shared'], dir);
    const agents = await runCli(['export', 'kiro-agents', '--out', 'shared'], dir);

    expect(both).toEqual([
      'rulebookguard-R-BIL-001.md',
      'rulebookguard-R-BIL-002.md',
      'rulebookguard-R-CLI-001.md',
      'rulebookguard-rule-author.md',
      'rulebookguard-rule-miner.md',
    ]);
    expect(steering.status).toBe(0);
    expect(steering.stdout).not.toContain('removed');
    expect(agents.status).toBe(0);
    expect((await readdir(join(dir, 'shared'))).sort()).toEqual(both);
  });
});
